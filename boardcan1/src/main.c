#include "S32K144.h"

#include "adc.h"
#include "can.h"

#include <stdint.h>


/* =========================================================
 * DEBUG MAIN
 * ========================================================= */

/*
 * Nhiệt độ dạng float
 */
volatile float temperature =
        0.0f;


/*
 * Nhiệt độ x100
 *
 * 28.53 -> 2853
 */
volatile uint16_t temperature_x100 =
        0U;


/* =========================================================
 * DEBUG CAN
 * ========================================================= */

volatile uint8_t tx_byte0 =
        0U;

volatile uint8_t tx_byte1 =
        0U;

volatile uint8_t tx_status =
        0U;

volatile uint32_t send_count =
        0U;


/* =========================================================
 * DELAY
 * ========================================================= */

static void delay(void)
{
    volatile uint32_t i;


    for (i = 0U;
         i < 1000000U;
         i++)
    {
        __asm("nop");
    }
}


/* =========================================================
 * MAIN
 * ========================================================= */

int main(void)
{
    uint8_t canData[2];


    /* =====================================================
     * ADC INIT
     * ===================================================== */

    if (ADC_Init() != ADC_OK)
    {
        while (1)
        {
        }
    }


    /* =====================================================
     * CAN INIT
     * ===================================================== */

    CAN_Init();


    if (can_last_status != CAN_OK)
    {
        while (1)
        {
        }
    }


    /* =====================================================
     * LOOP
     * ===================================================== */

    while (1)
    {
        /* =================================================
         * LM35
         *
         * Driver ADC tự:
         *
         * raw
         * -> voltage
         * -> temperature
         * -> x100
         * ================================================= */

        temperature_x100 =
                LM35_ReadTemperatureX100();


        /*
         * chỉ dùng để debug
         */
        temperature =
                ((float)
                 temperature_x100)
                /
                100.0f;


        /* =================================================
         * CAN DATA
         * ================================================= */

        canData[0] =
                (uint8_t)
                (
                    temperature_x100 >>
                    8
                );


        canData[1] =
                (uint8_t)
                (
                    temperature_x100 &
                    0xFFU
                );


        /* =================================================
         * DEBUG CAN BYTE
         * ================================================= */

        tx_byte0 =
                canData[0];


        tx_byte1 =
                canData[1];


        /* =================================================
         * SEND CAN
         * ================================================= */

        tx_status =
                CAN_Send(
                        0x123U,
                        canData,
                        2U);


        if (tx_status == CAN_OK)
        {
            send_count++;
        }


        delay();
    }
}
